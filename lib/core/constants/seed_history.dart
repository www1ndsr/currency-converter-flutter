// Используются как seed для аналитических экранов в Chrome (CORS-ограничение).

import 'package:decimal/decimal.dart';
import '../../data/models/historical_rate_point.dart';

class SeedHistory {
  static List<HistoricalRatePoint> getPoints(String charCode) {
    final code = charCode.toUpperCase();
    final data = _rawData[code];
    if (data == null) return [];
    final list = data.entries.map((e) {
      final date = _parseDate(e.key);
      return HistoricalRatePoint(
        date: date,
        effectiveDate: date,
        charCode: code,
        ratePerUnit: Decimal.parse(e.value),
      );
    }).toList();
    list.sort((a, b) => a.date.compareTo(b.date));
    return list;
  }

  static DateTime _parseDate(String s) {
    final parts = s.split('.');
    return DateTime(
      int.parse(parts[2]),
      int.parse(parts[1]),
      int.parse(parts[0]),
    );
  }

